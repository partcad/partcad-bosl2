"""A PartCAD ``basic`` repository plugin that serves BOSL2 as PartCAD parts.

BOSL2 (the Belfry OpenSCAD Library v2, BSD-2-Clause) is a large collection of
parametric OpenSCAD modules. This plugin exposes those modules as PartCAD
``scad`` parts *without vendoring* the library: the BOSL2 source is downloaded
on demand into a local cache the first time a part is listed or built, and each
part is generated by parsing a module's signature straight from that source.

PartCAD runs this script once per data request (via ``runpy``) with the request
in the global ``request`` and ``__name__`` set to the API ("get"); the answer is
returned in the global ``output`` as ``{"result": <value>}``. See the
"Repositories" section of the PartCAD documentation for the key conventions.

Each of the categories in :data:`CATEGORIES` is imported (in ``partcad.yaml``) as
a separate ``external`` package with its own ``subfolder``, so every key this
script sees is scoped, e.g. ``shapes3d/objects/part`` or
``gears/files/_bosl2_gears.scad``.

The module is import-safe (defines only functions and data at import time), so
the pure signature-parsing logic is unit-tested directly; see
``test_bosl2_repo.py``.
"""

