# ===========================================================================
# Signature parsing (pure)
# ===========================================================================


def strip_comments(text):
    """Remove block and line comments so they cannot break argument splitting."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"(?m)//.*$", "", text)
    return text


def _matching_paren(text, open_idx):
    """Index of the ``)`` matching the ``(`` at ``open_idx`` (quote-aware)."""
    depth = 0
    quote = None
    for i in range(open_idx, len(text)):
        ch = text[i]
        if quote:
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i
    return -1


def find_modules(text):
    """Return ``[(name, arg_string), ...]`` for top-level ``module NAME(...)``."""
    out = []
    for m in re.finditer(r"(?m)^module\s+([A-Za-z_]\w*)\s*\(", text):
        open_idx = m.end() - 1
        close_idx = _matching_paren(text, open_idx)
        if close_idx != -1:
            out.append((m.group(1), text[open_idx + 1 : close_idx]))
    return out


def split_args(arg_string):
    """Split an argument list on its top-level commas."""
    args = []
    depth = 0
    quote = None
    cur = ""
    for ch in arg_string:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
            cur += ch
        elif ch in "([{":
            depth += 1
            cur += ch
        elif ch in ")]}":
            depth -= 1
            cur += ch
        elif ch == "," and depth == 0:
            args.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur)
    return [a.strip() for a in args if a.strip()]


def split_name_default(arg):
    """Split ``name = default`` on the first top-level ``=``.

    Returns ``(name, default_or_None)``; a bare argument (no ``=``) is ``undef``
    in OpenSCAD, i.e. optional, and yields ``None``.
    """
    depth = 0
    quote = None
    for i, ch in enumerate(arg):
        if quote:
            if ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "=" and depth == 0:
            return arg[:i].strip(), arg[i + 1 :].strip()
    return arg.strip(), None


def classify_scalar(default):
    """Return ``(type, value)`` for a simple scalar default, else ``None``.

    Vectors, expressions and ``undef`` return ``None`` so the argument is left
    at the BOSL2 default rather than being exposed as a PartCAD parameter.
    """
    if default is None:
        return None
    d = default.strip()
    if d == "" or d == "undef":
        return None
    if d in ("true", "false"):
        return ("bool", d == "true")
    if re.fullmatch(r"[+-]?\d+", d):
        return ("int", int(d))
    if re.fullmatch(r"[+-]?(\d+\.\d*|\.\d+|\d+)([eE][+-]?\d+)?", d) and re.search(r"[.eE]", d):
        try:
            return ("float", float(d))
        except ValueError:
            return None
    if len(d) >= 2 and d[0] == '"' and d[-1] == '"':
        return ("string", d[1:-1])
    return None


